export const DEFAULT_LEGAL_CONTENT: LegalContent = {
  returns: returnsDefault,
  shipping: shippingDefault,
  privacy: privacyDefault,
  faq: faqDefault,
};

/** نسخة عميقة — حتى لا يعدّل محرر اللوحة الثوابت الافتراضية نفسها */
export const cloneLegalContent = <T>(value: T): T =>
  JSON.parse(JSON.stringify(value)) as T;

/**
 * يدمج ما هو محفوظ في Firestore فوق الافتراضي.
 * مستند ناقص (مثلاً حُفظت صفحة الشحن وحدها) يجب ألا يُفرغ بقية الصفحات.
 */
export const mergeLegalContent = (
  stored: Partial<LegalContent> | null | undefined,
): LegalContent => {
  const base = cloneLegalContent(DEFAULT_LEGAL_CONTENT);
  if (!stored) return base;
  return {
    returns: stored.returns ? { ...base.returns, ...stored.returns } : base.returns,
    shipping: stored.shipping
      ? { ...base.shipping, ...stored.shipping }
      : base.shipping,
    privacy: stored.privacy ? { ...base.privacy, ...stored.privacy } : base.privacy,
    faq: stored.faq ? { ...base.faq, ...stored.faq } : base.faq,
  };
};
